import type { Int8 } from '@stoktok/core';

export interface AssetRow {
  id: string;
  type: string;
  name: string;
  value: Int8;
  as_of: string;
}

export interface WatchlistRow {
  symbol: string;
  group_name: string;
  added_at: string;
}

/** Selected columns only. */
export interface PriceDailyRow {
  symbol: string;
  trade_date: string;
  close: number;
  source: string;
  fetched_at: string;
}

export interface SymbolRow {
  symbol: string;
  exchange: string | null;
}

/** Selected columns only: a daily close with its volume. */
export interface PriceCloseRow extends PriceDailyRow {
  volume: Int8;
}

/** Selected columns only. */
export interface PriceIntradayRow {
  symbol: string;
  ts: string;
  price: number;
  volume: Int8;
  source: string;
  fetched_at: string;
}

/** Upsert payload (all columns; R4 source + fetched_at). Integer VND (R2). */
export interface PriceIntradayInsert {
  symbol: string;
  ts: string;
  price: number;
  volume: number;
  source: string;
  fetched_at: string;
}

/** Upsert payload (all columns; R4 source + fetched_at). */
export interface PriceDailyInsert {
  symbol: string;
  trade_date: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
  foreign_net: number | null;
  source: string;
  fetched_at: string;
}

/** Upsert payload (all columns; R4 source + fetched_at). Integer VND (R2). */
export interface FinancialInsert {
  symbol: string;
  period: string;
  eps: number;
  bvps: number;
  revenue: number;
  net_income: number;
  source: string;
  fetched_at: string;
}

/** Selected columns only; bigint columns arrive as Int8. */
export interface FinancialRow {
  symbol: string;
  period: string;
  eps: Int8;
  bvps: Int8;
  revenue: Int8;
  net_income: Int8;
  source: string;
  fetched_at: string;
}

/** Upsert payload for `financial_lines` (R4 source + fetched_at). `value` is integer VND (R2). */
export interface FinancialLineInsert {
  symbol: string;
  period_kind: 'quarter' | 'year';
  period: string;
  statement: 'income' | 'balance' | 'cashflow';
  line: string;
  value: number;
  source: string;
  fetched_at: string;
}

/** Selected columns only; bigint columns arrive as Int8. */
export interface FinancialLineRow extends Omit<FinancialLineInsert, 'value'> {
  value: Int8;
}

/** Insert payload; `detected_at` defaults in the database. */
export interface DataGapInsert {
  /** null = market-wide gap. */
  symbol: string | null;
  data_type: string;
  from_ts: string;
  to_ts: string;
  source: string;
  fetched_at: string;
}

/** Insert payload; `id` is generated. Text fields are untrusted plain text (R9). */
export interface NewsInsert {
  url: string;
  title: string;
  excerpt: string;
  source: string;
  credibility: 'official_disclosure' | 'established_outlet';
  published_at: string;
  fetched_at: string;
  symbols: string[];
}

/** Selected columns only. */
export interface OpenGapRow {
  id: Int8;
  symbol: string | null;
  from_ts: string;
  to_ts: string;
}

/** Selected column only. */
export interface TradeDateRow {
  trade_date: string;
}

/** Upsert payload for `signals`; `id` and `created_at` are generated by the database. */
export interface SignalInsert {
  symbol: string;
  rule_id: string;
  horizon: 'medium';
  signal_date: string;
  status: 'ok' | 'suppressed';
  label: 'bullish' | 'bearish' | 'neutral' | null;
  value: number | null;
  data_fresh: boolean;
  reason_codes: string[];
  inputs_snapshot: Record<string, unknown>;
  rule_version: number;
  computed_at: string;
}

/** Selected columns only. `value` and `rule_version` may arrive as strings (PostgREST bigint). */
export interface SignalRow {
  symbol: string;
  rule_id: string;
  signal_date: string;
  status: string;
  label: string | null;
  value: number | string | null;
  reason_codes: string[] | null;
  inputs_snapshot: unknown;
  rule_version: number | string;
  computed_at: string;
}

/** Selected columns only. */
export interface SymbolSectorRow {
  symbol: string;
  sector: string | null;
  sector_source: string | null;
  sector_fetched_at: string | null;
}

/** Selected columns only; smallint[] arrives as number[], bigint columns as Int8. */
export interface LotteryDrawRow {
  game: string;
  draw_no: number;
  draw_date: string;
  numbers: number[];
  bonus: number | null;
  jackpot_vnd: Int8 | null;
  jackpot_winners: number | null;
  jackpot2_vnd: Int8 | null;
  jackpot2_winners: number | null;
  source: string;
  fetched_at: string;
}

/** Upsert payload (all columns; R4 source + fetched_at). Integer VND (R2). */
export interface LotteryDrawInsert {
  game: string;
  draw_no: number;
  draw_date: string;
  numbers: number[];
  bonus: number | null;
  jackpot_vnd: number | null;
  jackpot_winners: number | null;
  jackpot2_vnd: number | null;
  jackpot2_winners: number | null;
  source: string;
  fetched_at: string;
}

/** Selected columns only. */
export interface LotteryTicketRow {
  id: string;
  game: string;
  draw_no: number;
  lines: unknown;
  cost_vnd: Int8;
  channel: string;
  purchased_at: string;
  status: string;
  prize_tier: string | null;
  gross_vnd: Int8 | null;
  checked_at: string | null;
  raw_text: string | null;
  created_at: string;
}

/** Insert payload; id, status and result columns take their database defaults. Integer VND (R2). */
export interface LotteryTicketInsert {
  game: string;
  draw_no: number;
  lines: number[][];
  cost_vnd: number;
  channel: string;
  purchased_at: string;
  raw_text: string | null;
}
